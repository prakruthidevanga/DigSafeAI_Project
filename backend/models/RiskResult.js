const mongoose = require('mongoose');

const riskResultSchema = new mongoose.Schema({
  userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  location: { type: String, required: true },
  latitude: { type: Number, required: true },
  longitude: { type: Number, required: true },
  depth: { type: Number, required: true },
  radius: { type: Number, required: true },
  hazardScore: { type: Number, required: true },
  riskLevel: { type: String, required: true },
  warning: { type: String },
  nearbyUtilities: [{
    utilityType: String,
    source: String,
    dataSource: String,
    distance: Number,
  }],
  sensorInformation: {
    vibration: Number,
    acousticLevel: Number,
    soilCondition: Number,
    soilMoisture: Number,
    soilTemperature: Number,
    gasReading: Number,
    groundMovement: Number,
    ground_movement_mm: Number,
    source: String,
    dataSource: String,
  },
  imageInspection: {
    performed: { type: Boolean, default: false },
    model: String,
    detectionCount: Number,
    detections: [mongoose.Schema.Types.Mixed],
    visualConfirmation: mongoose.Schema.Types.Mixed,
  },
  hazardFormula: { type: String, default: 'H = 0.50*P + 0.20*D + 0.15*V + 0.10*M + 0.05*G' },
  formulaContributions: { type: mongoose.Schema.Types.Mixed },
  factors: { type: mongoose.Schema.Types.Mixed },
  assessmentMode: { type: String, default: 'INTEGRATED_HAZARD_ASSESSMENT' },
  models: { type: mongoose.Schema.Types.Mixed },
  availableModels: [{ type: String }],
  agreement: { type: Boolean },
  consensusClass: { type: String },
  confidence: { type: Number },
  contributingFactors: [{ type: String }],
  safetyRecommendations: [{ type: String }],
  explanation: { type: String },
  dataProvenance: {
    source: String,
    isSimulated: Boolean,
    dataQuality: String,
  },
  limitation: { type: String },
  createdAt: { type: Date, default: Date.now },
});

module.exports = mongoose.model('RiskResult', riskResultSchema);
