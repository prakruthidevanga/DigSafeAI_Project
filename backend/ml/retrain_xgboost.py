"""
XGBoost retraining script for DigSafe AI excavation-risk model.

PURPOSE
-------
The original xgboost.joblib artifact is permanently corrupted and cannot be loaded.
This script reconstructs a compatible XGBoost classifier using the same synthetic,
rule-based training scenario used to train the existing Random Forest artifact.

IMPORTANT LIMITATIONS
---------------------
- All training labels are generated by deterministic rules applied to synthetic data.
  They do NOT represent validated real-world excavation incident outcomes.
- This model is intended as experimental decision support ONLY.
- Do not use predictions from this model to make actual excavation safety decisions.
- Consult official utility records and qualified engineering personnel before any excavation.

SAFEGUARDS
----------
- The corrupted xgboost.joblib is NOT overwritten; output goes to xgboost_new.joblib.
- The existing random_forest.joblib is NOT touched.
- All artifacts are written only after successful load verification.
- Training scenarios match the nine-feature schema used by inference_service.py.
"""

import sys
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report, accuracy_score
from sklearn.preprocessing import LabelEncoder
import joblib
import xgboost as xgb

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
SCRIPT_DIR = Path(__file__).resolve().parent
MODELS_DIR = SCRIPT_DIR / "models"
NEW_XGB_PATH = MODELS_DIR / "xgboost_new.joblib"
ACTIVE_XGB_PATH = MODELS_DIR / "xgboost.joblib"
RF_PATH = MODELS_DIR / "random_forest.joblib"
FEATURE_COLUMNS_PATH = MODELS_DIR / "feature_columns.joblib"
LABEL_ENCODER_PATH = MODELS_DIR / "risk_label_encoder.joblib"

# ---------------------------------------------------------------------------
# Feature schema — must match inference_service.py and feature_columns.joblib
# ---------------------------------------------------------------------------
FEATURE_COLUMNS = [
    "start_lon",
    "start_lat",
    "geometry_length_approx_m",
    "coordinate_count_parsed",
    "distance_to_utility_m",
    "excavation_depth_m",
    "vibration_mm_s",
    "soil_moisture_pct",
    "ground_movement_mm",
]

LABEL_CLASSES = ["High", "Low", "Medium"]

RANDOM_SEED = 42
N_SAMPLES = 10000  # Larger dataset for better XGBoost generalisation


# ---------------------------------------------------------------------------
# Step 1 — Verify existing artifacts are intact and unchanged
# ---------------------------------------------------------------------------
def verify_existing_artifacts():
    print("\n[1/6] Verifying existing artifacts are intact...")
    for path, name in [(RF_PATH, "random_forest"), (FEATURE_COLUMNS_PATH, "feature_columns"),
                       (LABEL_ENCODER_PATH, "risk_label_encoder")]:
        if not path.is_file():
            raise FileNotFoundError(f"Required artifact missing: {path}")
        print(f"  OK  {name}: {path}")

    feature_columns = joblib.load(FEATURE_COLUMNS_PATH)
    if list(feature_columns) != FEATURE_COLUMNS:
        raise ValueError(
            f"Saved feature_columns mismatch.\n"
            f"  Expected: {FEATURE_COLUMNS}\n"
            f"  Found:    {list(feature_columns)}"
        )
    print(f"  OK  feature_columns match expected schema: {feature_columns}")

    label_encoder = joblib.load(LABEL_ENCODER_PATH)
    if sorted(label_encoder.classes_) != sorted(LABEL_CLASSES):
        raise ValueError(
            f"Saved label_encoder classes mismatch.\n"
            f"  Expected: {sorted(LABEL_CLASSES)}\n"
            f"  Found:    {sorted(label_encoder.classes_)}"
        )
    print(f"  OK  label_encoder classes: {label_encoder.classes_}")

    # Confirm Random Forest is loadable and untouched
    rf = joblib.load(RF_PATH)
    assert hasattr(rf, "predict_proba"), "RF model missing predict_proba"
    assert hasattr(rf, "classes_"), "RF model missing classes_"
    rf_type = type(rf).__name__
    # Handle both bare RandomForest and Pipeline wrappers
    n_est = getattr(rf, "n_estimators", None) or getattr(getattr(rf, "named_steps", {}), "n_estimators", "N/A")
    print(f"  OK  random_forest loaded: type={rf_type}, classes={rf.classes_}")

    return label_encoder


# ---------------------------------------------------------------------------
# Step 2 — Generate synthetic training data
#
# Nine-feature synthetic scenario using the same rule-based labeling approach:
#   depth > 5m                            → +1 risk
#   distance_to_utility < 3m             → +3 risk  (very close)
#   distance_to_utility < 10m            → +2 risk  (close)
#   distance_to_utility < 20m            → +1 risk  (nearby)
#   vibration_mm_s > 0.8                  → +1 risk
#   soil_moisture_pct > 0.7              → +1 risk
#   ground_movement_mm > 0.5             → +1 risk
#   coordinate_count_parsed > 50         → +1 risk  (complex geometry)
#
#   score >= 4 → High
#   score >= 2 → Medium
#   score  < 2 → Low
#
# Bengaluru bounding box approximation for realistic lat/lon values.
# ---------------------------------------------------------------------------
def generate_training_data(n_samples=N_SAMPLES, seed=RANDOM_SEED):
    print(f"\n[2/6] Generating {n_samples} synthetic training samples (seed={seed})...")
    rng = np.random.default_rng(seed)

    # Bengaluru approximate bounding box
    start_lon = rng.uniform(77.45, 77.75, n_samples)
    start_lat = rng.uniform(12.85, 13.10, n_samples)
    geometry_length_approx_m = rng.uniform(5.0, 2000.0, n_samples)
    coordinate_count_parsed = rng.integers(2, 200, n_samples).astype(float)
    distance_to_utility_m = rng.uniform(0.5, 100.0, n_samples)
    excavation_depth_m = rng.uniform(0.3, 12.0, n_samples)
    vibration_mm_s = rng.uniform(0.0, 1.0, n_samples)
    soil_moisture_pct = rng.uniform(0.0, 1.0, n_samples)
    ground_movement_mm = rng.uniform(0.0, 2.0, n_samples)

    # Rule-based risk scoring
    risk_score = np.zeros(n_samples, dtype=int)
    risk_score += (excavation_depth_m > 5).astype(int)
    risk_score += np.where(distance_to_utility_m < 3, 3,
                  np.where(distance_to_utility_m < 10, 2,
                  np.where(distance_to_utility_m < 20, 1, 0)))
    risk_score += (vibration_mm_s > 0.8).astype(int)
    risk_score += (soil_moisture_pct > 0.7).astype(int)
    risk_score += (ground_movement_mm > 0.5).astype(int)
    risk_score += (coordinate_count_parsed > 50).astype(int)

    labels = np.where(risk_score >= 4, "High",
              np.where(risk_score >= 2, "Medium", "Low"))

    df = pd.DataFrame({
        "start_lon": start_lon,
        "start_lat": start_lat,
        "geometry_length_approx_m": geometry_length_approx_m,
        "coordinate_count_parsed": coordinate_count_parsed,
        "distance_to_utility_m": distance_to_utility_m,
        "excavation_depth_m": excavation_depth_m,
        "vibration_mm_s": vibration_mm_s,
        "soil_moisture_pct": soil_moisture_pct,
        "ground_movement_mm": ground_movement_mm,
        "risk_label": labels,
    })

    dist = df["risk_label"].value_counts().to_dict()
    print(f"  Label distribution: {dist}")
    return df


# ---------------------------------------------------------------------------
# Step 3 — Train XGBoost classifier
# ---------------------------------------------------------------------------
def train_xgboost(df, label_encoder):
    print(f"\n[3/6] Training XGBoost classifier...")

    X = df[FEATURE_COLUMNS].copy()
    # The label encoder stores ["High", "Low", "Medium"] in alphabetical order.
    # XGBClassifier with sklearn API expects integer targets [0, 1, 2].
    # We encode using the saved LabelEncoder to guarantee the numeric class <-> label
    # mapping is identical to the one inference_service.py uses for decoding.
    y_str = df["risk_label"].values
    y = label_encoder.transform(y_str)  # ["High"->0, "Low"->1, "Medium"->2]

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, random_state=RANDOM_SEED, stratify=y
    )
    print(f"  Train: {len(X_train)} samples, Test: {len(X_test)} samples")

    # XGBoost classifier — use_label_encoder was removed in XGBoost >= 1.6
    model = xgb.XGBClassifier(
        n_estimators=200,
        max_depth=6,
        learning_rate=0.1,
        subsample=0.8,
        colsample_bytree=0.8,
        eval_metric="mlogloss",
        random_state=RANDOM_SEED,
        n_jobs=-1,
    )
    model.fit(X_train, y_train, eval_set=[(X_test, y_test)], verbose=False)

    y_pred = model.predict(X_test)
    accuracy = accuracy_score(y_test, y_pred)
    print(f"  Holdout accuracy: {accuracy:.4f} (against synthetic labels -- not real-world validation)")
    print("\n  Classification report (synthetic labels only):")
    # model.classes_ will be [0, 1, 2]; map back to strings for report
    int_to_str = {i: label for i, label in enumerate(label_encoder.classes_)}
    target_names = [int_to_str[c] for c in sorted(int_to_str.keys())]
    print(classification_report(y_test, y_pred, target_names=target_names))

    return model, accuracy


# ---------------------------------------------------------------------------
# Step 4 — Validate the new model before saving
# ---------------------------------------------------------------------------
def validate_new_model(model, label_encoder):
    print("\n[4/6] Validating new XGBoost model...")

    # Must have required interface
    assert callable(getattr(model, "predict", None)), "predict() missing"
    assert callable(getattr(model, "predict_proba", None)), "predict_proba() missing"
    assert hasattr(model, "classes_"), "classes_ missing"

    # Verify feature order matches saved schema
    if hasattr(model, "feature_names_in_"):
        actual = list(model.feature_names_in_)
        assert actual == FEATURE_COLUMNS, (
            f"Feature order mismatch: {actual} != {FEATURE_COLUMNS}"
        )
    print("  OK  predict, predict_proba, classes_ present")

    # Run a known test inference
    test_row = pd.DataFrame([{
        "start_lon": 77.5946,
        "start_lat": 12.9716,
        "geometry_length_approx_m": 150.0,
        "coordinate_count_parsed": 10.0,
        "distance_to_utility_m": 2.0,   # very close → should be HIGH
        "excavation_depth_m": 6.0,
        "vibration_mm_s": 0.9,
        "soil_moisture_pct": 0.8,
        "ground_movement_mm": 0.7,
    }], columns=FEATURE_COLUMNS)

    predicted = model.predict(test_row)
    probas = model.predict_proba(test_row)

    assert len(predicted) == 1, "Expected 1 prediction"
    assert len(probas) == 1 and len(probas[0]) == len(model.classes_), "Bad proba shape"
    proba_sum = float(sum(probas[0]))
    assert abs(proba_sum - 1.0) < 0.01, f"Probabilities do not sum to 1: {proba_sum}"

    # Decode the predicted class using the saved label encoder
    class_idx = int(predicted[0])
    predicted_label = label_encoder.inverse_transform([class_idx])[0]
    print(f"  OK  Test inference passed: class={predicted_label}, proba_sum={proba_sum:.5f}")
    print(f"      (Close utility + deep excavation → expected High; got {predicted_label})")

    return True


# ---------------------------------------------------------------------------
# Step 5 — Save new model (separate file, do NOT overwrite original)
# ---------------------------------------------------------------------------
def save_new_model(model):
    print(f"\n[5/6] Saving new XGBoost model to: {NEW_XGB_PATH}")
    print(f"      The corrupted original is NOT modified.")
    joblib.dump(model, NEW_XGB_PATH)
    assert NEW_XGB_PATH.is_file(), "Save failed -- file not created"
    size_kb = NEW_XGB_PATH.stat().st_size / 1024
    print(f"  OK  Saved ({size_kb:.1f} KB)")


# ---------------------------------------------------------------------------
# Step 6 — Verify saved model round-trips correctly
# ---------------------------------------------------------------------------
def verify_saved_model():
    print(f"\n[6/6] Verifying saved model round-trips from disk...")
    reloaded = joblib.load(NEW_XGB_PATH)
    assert hasattr(reloaded, "predict_proba"), "Reloaded model missing predict_proba"
    assert hasattr(reloaded, "classes_"), "Reloaded model missing classes_"
    if hasattr(reloaded, "feature_names_in_"):
        assert list(reloaded.feature_names_in_) == FEATURE_COLUMNS, \
            "Reloaded feature order mismatch"
    print(f"  OK  Round-trip load successful")
    print(f"      classes_: {reloaded.classes_}")
    return reloaded


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    print("=" * 70)
    print("DigSafe AI — XGBoost Retraining Script")
    print("=" * 70)
    print("""
IMPORTANT: This script uses SYNTHETIC, RULE-BASED training labels.
  - Labels are generated by deterministic rules, not real incident data.
  - The resulting model is experimental decision support ONLY.
  - Do NOT use predictions for actual excavation safety decisions.
  - Do NOT present as validated or certified safety tooling.
""")

    try:
        label_encoder = verify_existing_artifacts()
        df = generate_training_data()
        model, accuracy = train_xgboost(df, label_encoder)
        validate_new_model(model, label_encoder)
        save_new_model(model)
        verify_saved_model()
    except Exception as exc:
        print(f"\nFAILED: {type(exc).__name__}: {exc}")
        return 1

    print("\n" + "=" * 70)
    print("SUCCESS — XGBoost retraining complete.")
    print(f"  New model:          {NEW_XGB_PATH}")
    print(f"  Original corrupted: {ACTIVE_XGB_PATH}  (unchanged)")
    print(f"  Holdout accuracy:   {accuracy:.4f}  (against synthetic labels only)")
    print("""
NEXT STEP (manual):
  After running the full test suite and confirming all tests pass,
  replace the active artifact:
    Copy-Item backend\\ml\\models\\xgboost_new.joblib backend\\ml\\models\\xgboost.joblib
  The retrain script will not do this automatically.
""")
    result = {
        "status": "SUCCESS",
        "new_artifact": str(NEW_XGB_PATH),
        "original_artifact": str(ACTIVE_XGB_PATH),
        "holdout_accuracy_synthetic": round(accuracy, 4),
        "feature_columns": FEATURE_COLUMNS,
        "label_classes": LABEL_CLASSES,
        "warning": "Synthetic labels only. Not validated for real-world excavation safety.",
    }
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
